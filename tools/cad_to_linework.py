"""Extract the Option A plan linework from exiting_v2 (DXF) into js/cad-linework.js.

The viewer draws this linework in Plan GF / Plan 1F so the plans match the CAD file exactly.

Usage (needs ezdxf: pip install ezdxf):
    1. In AutoCAD: SAVEAS exiting_v2.dwg -> DXF 2018  (or use accoreconsole)
    2. python tools/cad_to_linework.py path/to/exiting_v2.dxf

CAD -> data: x = (cadX + 106492) / 1000 (upper floor: cadX + 80922), z = (cadY - 12950) / 1000
"""
import json
import math
import sys
from pathlib import Path

import ezdxf
from ezdxf import bbox

# plan windows in CAD units (x range, y range) and x offset to data coords
FLOORS = {
    "GF": {"x": (-106600, -94500), "y": (12900, 36000), "dx": 106492},
    "1F": {"x": (-81000, -68900), "y": (12900, 36000), "dx": 80922},
}
DY = -12950
SKIP_LAYERS = {"EX-ROOM", "EX-DIM", "EX-TEXT", "EX-PHOTO", "EX-DEFECT", "EX-LEVEL", "TAXE", "Defpoints"}


def flatten(e, depth=0):
    """Yield primitive entities, exploding block references."""
    t = e.dxftype()
    if t == "INSERT":
        if depth > 4:
            return
        for v in e.virtual_entities():
            yield from flatten(v, depth + 1)
    else:
        yield e


def segments(e):
    t = e.dxftype()
    if t == "LINE":
        s, d = e.dxf.start, e.dxf.end
        return [((s.x, s.y), (d.x, d.y))]
    if t in ("LWPOLYLINE", "POLYLINE"):
        pts = [(p[0], p[1]) for p in (e.get_points() if t == "LWPOLYLINE" else [v.dxf.location for v in e.vertices])]
        if e.closed if t == "LWPOLYLINE" else e.is_closed:
            pts.append(pts[0])
        return list(zip(pts, pts[1:]))
    if t in ("ARC", "CIRCLE"):
        c, r = e.dxf.center, e.dxf.radius
        a0, a1 = (math.radians(e.dxf.start_angle), math.radians(e.dxf.end_angle)) if t == "ARC" else (0, 2 * math.pi)
        if a1 <= a0:
            a1 += 2 * math.pi
        n = max(6, int((a1 - a0) / (math.pi / 16)))
        pts = [(c.x + r * math.cos(a0 + (a1 - a0) * i / n), c.y + r * math.sin(a0 + (a1 - a0) * i / n)) for i in range(n + 1)]
        return list(zip(pts, pts[1:]))
    return []


def main(path):
    doc = ezdxf.readfile(path)
    msp = doc.modelspace()
    out = {k: [] for k in FLOORS}
    for top in msp:
        if top.dxf.layer in SKIP_LAYERS:
            continue
        for e in flatten(top):
            if e.dxf.layer in SKIP_LAYERS:
                continue
            for (x1, y1), (x2, y2) in segments(e):
                for k, f in FLOORS.items():
                    inside = all(f["x"][0] < x < f["x"][1] and f["y"][0] < y < f["y"][1] for x, y in ((x1, y1), (x2, y2)))
                    if inside and (abs(x1 - x2) + abs(y1 - y2)) > 1:
                        out[k].append([round((x1 + f["dx"]) / 1000, 4), round((y1 + DY) / 1000, 4),
                                       round((x2 + f["dx"]) / 1000, 4), round((y2 + DY) / 1000, 4)])
    # the big markup circle on layer 0 is not part of the plan
    for k in out:
        out[k] = [s for s in out[k] if math.hypot(s[0] - s[2], s[1] - s[3]) < 20]
    target = Path(__file__).resolve().parent.parent / "js" / "cad-linework.js"
    target.write_text(
        "// GENERATED by tools/cad_to_linework.py from exiting_v2 — do not edit by hand.\n"
        "// Segments [x1, z1, x2, z2] in data metres.\n"
        f"export const CAD_LINES = {json.dumps(out, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print({k: len(v) for k, v in out.items()}, "->", target)


if __name__ == "__main__":
    main(sys.argv[1])
